// Creates a DEVELOPMENT-ONLY env file with every configuration variable and two fresh audit keys.
// Usage: node scripts/create-dev-env.mjs [targetPath]   (default: .env in the current directory)
// It never prints key values and never overwrites an existing file.
import { randomBytes } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';

const KEY_BYTES = 32;

function newKey() {
  return randomBytes(KEY_BYTES).toString('base64');
}

/** Two independent keys; equal keys are rejected at startup, so regenerate on the (astronomically unlikely) tie. */
function newKeyPair() {
  const encryptionKey = newKey();
  let userRefKey = newKey();
  while (userRefKey === encryptionKey) userRefKey = newKey();
  return { encryptionKey, userRefKey };
}

function render({ encryptionKey, userRefKey }) {
  return [
    '# Guardian Integration Gateway: development only, never commit, never reuse in production.',
    '# Generated by scripts/create-dev-env.mjs. Production keys come from a KMS or secret manager (docs/encryption.md).',
    '',
    '# development | test | production',
    'NODE_ENV=development',
    'PORT=3000',
    '# fatal | error | warn | info | debug | trace | silent',
    'LOG_LEVEL=info',
    'REQUEST_BODY_LIMIT_BYTES=16384',
    '',
    '# Audit store (JSON Lines, append-only)',
    'AUDIT_FILE_PATH=./data/audit.jsonl',
    '# 32 random bytes, base64: encrypts the original message (AES-256-GCM)',
    `AUDIT_ENCRYPTION_KEY=${encryptionKey}`,
    'AUDIT_ENCRYPTION_KEY_ID=v1',
    '# A second, different 32-byte key: HMAC that pseudonymizes userId as userRef',
    `AUDIT_USER_REF_KEY=${userRefKey}`,
    '',
    '# Simulated AI provider; failures: never | always | first:<n>',
    'AI_PROVIDER_DELAY_MS=2000',
    'AI_PROVIDER_FAILURES=never',
    'AI_PROVIDER_TIMEOUT_MS=5000',
    '',
    '# Circuit breaker',
    'CIRCUIT_BREAKER_FAILURE_THRESHOLD=3',
    'CIRCUIT_BREAKER_COOLDOWN_MS=30000',
    '',
  ].join('\n');
}

const target = resolve(process.argv[2] ?? '.env');

try {
  // 'wx' fails if the file exists, atomically: an existing env file (and its keys) is never replaced.
  writeFileSync(target, render(newKeyPair()), { encoding: 'utf8', mode: 0o600, flag: 'wx' });
} catch (error) {
  const code = error instanceof Error && 'code' in error ? String(error.code) : 'UNKNOWN';
  const reason = code === 'EEXIST' ? 'it already exists; delete it first if you really want new keys' : code;
  process.stderr.write(`Refusing to write ${target}: ${reason}\n`);
  process.exit(1);
}

process.stdout.write(`Created ${target}\n`);
